// Extracts the real source of every examples/*.example.{ts,html} file into a
// sibling *.snippet.ts artifact, pre-highlighted with Shiki (dual light/dark
// themes as CSS variables). Snippets are gitignored build outputs consumed by
// DemoExample, so example source is never hand-copied (spec 002).
import { globSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative } from 'node:path';
import { codeToHtml } from 'shiki';

const EXAMPLES_GLOB = 'libs/ng-component-demos/src/lib/**/examples/*.example.@(ts|html)';
const DEMO_SNIPPET_MODULE = 'libs/ng-component-demos/src/lib/_demo-ui/demo-snippet';
const LANG_BY_EXTENSION = { ts: 'typescript', html: 'html' };

async function highlight(source, lang) {
  return codeToHtml(source, {
    lang,
    themes: { light: 'github-light', dark: 'github-dark' },
    defaultColor: false,
  });
}

function snippetImportPath(snippetPath) {
  const path = relative(dirname(snippetPath), DEMO_SNIPPET_MODULE).replace(/\\/g, '/');
  return path.startsWith('.') ? path : `./${path}`;
}

async function run() {
  const files = globSync(EXAMPLES_GLOB).sort();
  for (const file of files) {
    const extension = file.endsWith('.html') ? 'html' : 'ts';
    const lang = LANG_BY_EXTENSION[extension];
    const source = readFileSync(file, 'utf-8').replace(/\s+$/, '\n');
    const html = await highlight(source, lang);

    const snippetPath = file.replace(/\.example\.(ts|html)$/, `.${extension}.snippet.ts`);
    const contents =
      `// Generated by generate-snippets.mjs. Do not edit; regenerate with \`nx generate-snippets ng-component-demos\`.\n` +
      `import type { DemoSnippet } from '${snippetImportPath(snippetPath)}';\n\n` +
      `export const snippet: DemoSnippet = ${JSON.stringify({ source, html, lang }, null, 2)};\n`;
    writeFileSync(snippetPath, contents);
  }
  console.log(`generate-snippets: wrote ${files.length} snippet(s).`);
}

run().catch((error) => {
  console.error(error);
  process.exit(1);
});
